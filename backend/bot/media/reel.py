"""Reel video: AI image per scene + TTS voiceover + timed captions, assembled with ffmpeg."""

import logging
import random
import subprocess
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

from app.config import PROJECT_ROOT
from bot.media.ai_images import MediaError, generate_image
from bot.media.tts import synthesize
from bot.settings import BrandKit, Voiceover, load_brand_kit
from bot.writer.schemas import ReelDraft

logger = logging.getLogger(__name__)

REEL_SIZE = {"width": 1080, "height": 1920}
FPS = 30
ZOOM = 0.12
SCENE_TAIL = 0.3  # seconds of breathing room after each voiceover line
MAX_CHUNK_WORDS = 3
MAX_CHUNK_CHARS = 18
MUSIC_DIR = PROJECT_ROOT / "assets" / "music"
MUSIC_VOLUME = 0.12


@dataclass
class Caption:
    text: str
    start: float
    end: float
    highlight: int  # 1-based index of the word drawn in the accent color
    speaker: str = ""  # character name shown above the caption while they speak


def ffmpeg_exe() -> str:
    import imageio_ffmpeg

    return imageio_ffmpeg.get_ffmpeg_exe()


def caption_chunks(text: str, duration: float) -> list[Caption]:
    """Split a voiceover line into short caption chunks timed by character count."""
    chunks: list[list[str]] = []
    for word in text.split():
        current = chunks[-1] if chunks else None
        if (
            current is None
            or len(current) >= MAX_CHUNK_WORDS
            or len(" ".join([*current, word])) > MAX_CHUNK_CHARS
        ):
            chunks.append([word])
        else:
            current.append(word)

    weights = [len(" ".join(c)) + 1 for c in chunks]
    total = sum(weights) or 1
    captions, start = [], 0.0
    for words, weight in zip(chunks, weights):
        end = start + duration * weight / total
        longest = max(range(len(words)), key=lambda i: len(words[i].strip(".,!?")))
        captions.append(Caption(" ".join(words), start, end, longest + 1))
        start = end
    return captions


def render_reel(
    draft: ReelDraft, out_dir: Path, brand: BrandKit | None = None, voice: Voiceover | None = None
) -> list[Path]:
    """Render `video.mp4` and `cover.jpg` into out_dir and return their paths."""
    brand = brand or load_brand_kit()
    work = out_dir / "reel_work"
    work.mkdir(parents=True, exist_ok=True)

    voices = prepare_voiceovers([scene.voiceover for scene in draft.scenes], work, brand, voice)

    # Images one at a time: image models have small per-minute quotas. Scenes already
    # generated by an earlier, interrupted attempt are reused.
    images = []
    for i, scene in enumerate(draft.scenes):
        existing = sorted(work.glob(f"scene_{i}.[jp][pn]g")) + sorted(work.glob(f"scene_{i}.jpeg"))
        images.append(
            existing[0]
            if existing
            else generate_image(
                scene.image_prompt,
                "9:16",
                work / f"scene_{i}",
                draft.visual_style,
                brand.image_style,
            )
        )
    assets = [(image, audio, duration) for image, (audio, duration) in zip(images, voices)]

    overlays = render_overlays(
        [(s.on_screen_text, s.voiceover, d) for s, (_, d) in zip(draft.scenes, voices)], work, brand
    )
    clips = []
    for i, ((image, audio, duration), scene_overlays) in enumerate(zip(assets, overlays)):
        clip = work / f"scene_{i}.mp4"
        render_scene(image, audio, duration, scene_overlays, clip, zoom_in=i % 2 == 0)
        clips.append(clip)

    video = out_dir / "video.mp4"
    concat_clips(clips, work, video)
    cover = out_dir / "cover.jpg"
    _render_cover(draft, assets[0][0], cover, brand)
    cleanup_work(work)
    return [video, cover]


def prepare_voiceovers(
    lines: list[str], work: Path, brand: BrandKit, voice: Voiceover | None = None
) -> list[tuple[Path, float]]:
    """TTS each line (reusing WAVs from an earlier attempt); return (audio, scene seconds)."""
    voice = voice or brand.voiceover

    def voiceover(item: tuple[int, str]) -> tuple[Path, float]:
        i, text = item
        audio = work / f"scene_{i}.wav"
        spoken = _wav_seconds(audio) if audio.is_file() else synthesize(text, audio, voice)
        return audio, spoken + SCENE_TAIL

    with ThreadPoolExecutor(max_workers=4) as pool:
        return list(pool.map(voiceover, enumerate(lines)))


def cleanup_work(work: Path) -> None:
    for leftover in work.glob("*"):
        if leftover.name.startswith("clip_"):
            continue  # generated video clips are kept so a retry never pays for them twice
        if leftover.suffix in (".mp4", ".txt") or leftover.name.startswith(("overlay_", "frame_")):
            leftover.unlink()


def _wav_seconds(path: Path) -> float:
    import wave

    with wave.open(str(path)) as audio:
        return audio.getnframes() / audio.getframerate()


def render_overlays(
    scenes: list[tuple[str, str, float]], work: Path, brand: BrandKit, caption_bottom: int = 470
) -> list[list[tuple[Path, Caption]]]:
    """Transparent caption overlays per scene; each scene is (top text, voiceover, seconds)."""
    return render_caption_overlays(
        [(top, caption_chunks(text, duration - SCENE_TAIL)) for top, text, duration in scenes],
        work,
        brand,
        caption_bottom,
    )


def render_caption_overlays(
    scenes: list[tuple[str, list[Caption]]], work: Path, brand: BrandKit, caption_bottom: int = 470
) -> list[list[tuple[Path, Caption]]]:
    """Transparent overlays for already-timed captions; each scene is (top text, captions)."""
    from playwright.sync_api import sync_playwright

    from bot.media.render import TEMPLATES, _font_faces

    template = TEMPLATES.get_template("reel_frame.html")
    faces = _font_faces(brand)
    result = []
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch()
        try:
            page = browser.new_page(viewport=REEL_SIZE)
            for i, (top_text, captions) in enumerate(scenes):
                scene_overlays = []
                for j, caption in enumerate(captions):
                    page.set_content(
                        template.render(
                            brand=brand,
                            font_faces=faces,
                            top_text=top_text,
                            caption=caption.text,
                            highlight=caption.highlight,
                            speaker=caption.speaker,
                            caption_bottom=caption_bottom,
                        ),
                        wait_until="load",
                    )
                    path = work / f"overlay_{i}_{j:02d}.png"
                    page.screenshot(path=path, omit_background=True)
                    scene_overlays.append((path, caption))
                result.append(scene_overlays)
        finally:
            browser.close()
    return result


def render_scene(
    image: Path,
    audio: Path,
    duration: float,
    overlays: list[tuple[Path, Caption]],
    out: Path,
    zoom_in: bool = True,
    zoom_amount: float = ZOOM,
    motion: str | None = None,
) -> None:
    """One scene clip: background (camera move, or static when zoom_amount is 0) + captions.

    `motion` picks a camera move (see CAMERA_MOVES); otherwise zoom_in chooses push or pull."""
    frames = max(round(duration * FPS), 1)
    if motion == "video":
        inputs = ["-i", str(image)]
        background = (
            "[0:v]scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920,"
            f"fps={FPS},setsar=1,tpad=stop_mode=clone:stop_duration={duration:.3f},"
            f"trim=duration={duration:.3f}[v0]"
        )
    elif zoom_amount:
        move = motion or ("slow_push_in" if zoom_in else "slow_pull_out")
        z, x, y = camera_move(move, frames, zoom_amount)
        inputs = ["-i", str(image)]
        background = (
            f"[0:v]scale=2160:3840:force_original_aspect_ratio=increase,crop=2160:3840,"
            f"zoompan=z='{z}':x='{x}':y='{y}'"
            f":d={frames}:s=1080x1920:fps={FPS},setsar=1[v0]"
        )
    else:
        inputs = ["-loop", "1", "-t", f"{duration:.3f}", "-i", str(image)]
        background = (
            "[0:v]scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920,"
            f"fps={FPS},setsar=1[v0]"
        )
    for path, _ in overlays:
        inputs += ["-loop", "1", "-t", f"{duration:.3f}", "-i", str(path)]
    inputs += ["-i", str(audio)]

    graph = [background]
    for k, (_, caption) in enumerate(overlays, 1):
        end = duration if k == len(overlays) else caption.end
        graph.append(
            f"[v{k - 1}][{k}:v]overlay=0:0:enable='between(t,{caption.start:.3f},{end:.3f})'[v{k}]"
        )
    audio_index = len(overlays) + 1
    graph.append(f"[{audio_index}:a]aresample=44100,apad=whole_dur={duration:.3f}[a]")

    _run(
        [
            *inputs,
            "-filter_complex", ";".join(graph),
            "-map", f"[v{len(overlays)}]", "-map", "[a]",
            "-t", f"{duration:.3f}", "-r", str(FPS),
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-b:a", "160k", "-ac", "2",
            str(out),
        ]
    )  # fmt: skip


def camera_move(move: str, frames: int, amount: float = ZOOM) -> tuple[str, str, str]:
    """zoompan (z, x, y) expressions for a named camera move over `frames` frames."""
    progress = f"on/{frames}"
    center_x, center_y = "iw/2-(iw/zoom/2)", "ih/2-(ih/zoom/2)"
    span_x, span_y = "(iw-iw/zoom)", "(ih-ih/zoom)"
    held = f"{1 + amount}"
    moves = {
        "slow_push_in": (f"1+{amount}*{progress}", center_x, center_y),
        "slow_pull_out": (f"{1 + amount}-{amount}*{progress}", center_x, center_y),
        "pan_left": (held, f"{span_x}*(1-{progress})", center_y),
        "pan_right": (held, f"{span_x}*{progress}", center_y),
        "tilt_up": (held, center_x, f"{span_y}*(1-{progress})"),
        "static": (f"1+{amount / 4}", center_x, center_y),
    }
    return moves.get(move, moves["slow_push_in"])


def concat_clips(clips: list[Path], work: Path, out: Path) -> None:
    listing = work / "clips.txt"
    listing.write_text("".join(f"file '{clip.resolve()}'\n" for clip in clips))
    joined = work / "joined.mp4"
    _run(["-f", "concat", "-safe", "0", "-i", str(listing), "-c", "copy", str(joined)])

    tracks = sorted(MUSIC_DIR.glob("*.mp3")) if MUSIC_DIR.is_dir() else []
    if tracks:
        music = random.choice(tracks)
        _run(
            [
                "-i", str(joined), "-stream_loop", "-1", "-i", str(music),
                "-filter_complex",
                f"[1:a]volume={MUSIC_VOLUME}[m];[0:a][m]amix=inputs=2:duration=first:normalize=0[a]",
                "-map", "0:v", "-map", "[a]", "-c:v", "copy", "-c:a", "aac", "-b:a", "160k",
                "-movflags", "+faststart", str(out),
            ]
        )  # fmt: skip
    else:
        _run(["-i", str(joined), "-c", "copy", "-movflags", "+faststart", str(out)])


def _render_cover(draft: ReelDraft, background: Path, out: Path, brand: BrandKit) -> None:
    from playwright.sync_api import sync_playwright

    from bot.media.render import TEMPLATES, _data_uri, _font_faces

    html = TEMPLATES.get_template("reel_frame.html").render(
        brand=brand,
        font_faces=_font_faces(brand),
        background_uri=_data_uri(background),
        cover_title=draft.hook,
    )
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch()
        try:
            page = browser.new_page(viewport=REEL_SIZE)
            page.set_content(html, wait_until="load")
            page.screenshot(path=out, type="jpeg", quality=92)
        finally:
            browser.close()


def _run(args: list[str]) -> None:
    command = [ffmpeg_exe(), "-y", "-hide_banner", "-loglevel", "error", *args]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        logger.error("Video assembly failed: %s", result.stderr.strip()[-2000:])
        raise MediaError("We couldn't put the video together. Please try again.")


def video_duration(path: Path) -> float | None:
    """Best-effort duration read from ffmpeg's stderr (no ffprobe in the bundled build)."""
    result = subprocess.run(
        [ffmpeg_exe(), "-hide_banner", "-i", str(path)], capture_output=True, text=True, check=False
    )
    for line in result.stderr.splitlines():
        if "Duration:" in line:
            h, m, s = line.split("Duration:")[1].split(",")[0].strip().split(":")
            return int(h) * 3600 + int(m) * 60 + float(s)
    return None
